import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { useJsonViewerDrawer } from '@/shared/composables/useJsonViewerDrawer'

const drawer = useJsonViewerDrawer()
beforeEach(() => { vi.useFakeTimers(); drawer.close() })
afterEach(() => { drawer.close(); vi.useRealTimers() })

describe('全局 JSON 抽屉悬浮与固定', () => {
  it('经过 180ms 才读取触发区数据；提前移出不打开', () => {
    const owner = Symbol()
    const source = vi.fn(() => ({ data: '{"ok":true}', title: '请求正文' }))
    drawer.enterTrigger(owner, source)
    vi.advanceTimersByTime(179)
    expect(source).not.toHaveBeenCalled()
    drawer.leaveTrigger(owner)
    vi.advanceTimersByTime(300)
    expect(drawer.isOpen.value).toBe(false)
    drawer.enterTrigger(owner, source)
    vi.advanceTimersByTime(180)
    expect(drawer.source.value?.title).toBe('请求正文')
    expect(drawer.isOpen.value).toBe(true)
  })

  it('跨越触发区到抽屉时保持开启，全部移出后延迟 260ms 关闭', () => {
    const owner = Symbol()
    drawer.enterTrigger(owner, () => ({ data: '{}' }))
    vi.advanceTimersByTime(180)
    drawer.leaveTrigger(owner)
    vi.advanceTimersByTime(200)
    drawer.enterDrawer()
    vi.advanceTimersByTime(500)
    expect(drawer.isOpen.value).toBe(true)
    drawer.leaveDrawer()
    vi.advanceTimersByTime(259)
    expect(drawer.isOpen.value).toBe(true)
    vi.advanceTimersByTime(1)
    expect(drawer.isOpen.value).toBe(false)
    expect(drawer.source.value).toBeNull()
  })

  it('固定内容不会被悬浮其他 JSON 替换；显式点击可以切换固定内容', () => {
    const first = Symbol(), second = Symbol()
    drawer.pinSource(first, { data: '[1]', title: '第一份' })
    drawer.releaseTrigger(first)
    drawer.enterTrigger(second, () => ({ data: '[2]', title: '第二份' }))
    vi.advanceTimersByTime(1000)
    expect(drawer.source.value?.title).toBe('第一份')
    drawer.pinSource(second, { data: '[2]', title: '第二份' })
    expect(drawer.source.value?.title).toBe('第二份')
    drawer.leaveTrigger(second)
    vi.advanceTimersByTime(1000)
    expect(drawer.isOpen.value).toBe(true)
    drawer.togglePin()
    vi.advanceTimersByTime(260)
    expect(drawer.isOpen.value).toBe(false)
  })

  it('快速切换区域时旧区域的移出事件不会取消新预览', () => {
    const first = Symbol(), second = Symbol()
    drawer.enterTrigger(first, () => ({ data: '1' }))
    vi.advanceTimersByTime(100)
    drawer.enterTrigger(second, () => ({ data: '2' }))
    drawer.leaveTrigger(first)
    vi.advanceTimersByTime(180)
    expect(drawer.source.value?.data).toBe('2')
    drawer.close()
    vi.runAllTimers()
    expect(drawer.isOpen.value).toBe(false)
  })
})
